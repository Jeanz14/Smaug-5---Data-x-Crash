using System;
using System.IO;
using UnityEngine;
#if UNITY_MSBUILD_ENABLED
using System.Linq;
using System.Xml.Linq;
using UnityEditor;
using IOPath = System.IO.Path;
#endif

namespace Microsoft.Unity.VisualStudio.Editor
{
	internal static class MSBuildProjectIntegration
	{
		private const string GeneratedPropsRelativePath = "Library/VisualStudioEditor/MSBuild/VisualStudioEditor.Generated.props";

		public static void RemoveGeneratedProps()
		{
			var path = FileUtility.GetAssetFullPath(GeneratedPropsRelativePath);
			FileUtility.SafeDelete(path);
		}

#if UNITY_MSBUILD_ENABLED
		public static string SolutionFileName
		{
			get
			{
				return IOPath.GetFileName(SolutionFilePath);
			}
		}

		public static string SolutionFilePath
		{
			get
			{
				var projectDirectory = GetProjectDirectory();
				var defaultSolution = IOPath.Combine(projectDirectory, IOPath.GetFileName(projectDirectory) + ".slnx");
				if (File.Exists(defaultSolution))
					return defaultSolution;

				return Directory
					.GetFiles(projectDirectory, "*.slnx", SearchOption.TopDirectoryOnly)
					.OrderByDescending(File.GetLastWriteTimeUtc)
					.FirstOrDefault() ?? defaultSolution;
			}
		}

		public static bool Update(IVisualStudioInstallation installation)
		{
			installation?.CreateExtraFiles(GetProjectDirectory());

			var analyzers = installation != null && installation.SupportsAnalyzers
				? installation.GetAnalyzers()
				: Array.Empty<string>();

			var document = CreateGeneratedProps(
				analyzers,
				EditorUserBuildSettings.activeBuildTarget,
				Application.unityVersion,
				installation != null);
			return WriteIfChanged(FileUtility.GetAssetFullPath(GeneratedPropsRelativePath), document.ToString());
		}

		internal static XDocument CreateGeneratedProps(
			string[] analyzers,
			BuildTarget buildTarget,
			string unityVersion,
			bool isActive)
		{
			var buildTargetValue = buildTarget + ":" + (int)buildTarget;
			var itemGroup = new XElement(
				"ItemGroup",
				new XAttribute("Condition", "'$(UnityVisualStudioEditorActive)' == 'true' And '$(DesignTimeBuild)' == 'true' And '$(IsEntryPointProject)' != 'true' And '$(MSBuildProjectName)' != 'Main.EntryPoint'"),
				analyzers
					.Where(File.Exists)
					.Select(FileUtility.GetAbsolutePath)
					.Distinct(StringComparer.OrdinalIgnoreCase)
					.OrderBy(path => path, StringComparer.OrdinalIgnoreCase)
					.Select(path => new XElement("Analyzer", new XAttribute("Include", EscapeForMSBuild(path.NormalizeWindowsToUnix())))));

			var document = new XDocument(
				new XElement(
					"Project",
					new XComment("Generated by com.unity.ide.visualstudio. Do not edit."),
					new XElement(
						"PropertyGroup",
						new XElement("UnityVisualStudioEditorActive", isActive.ToString().ToLowerInvariant()),
						new XElement("UnityVisualStudioBuildTarget", buildTargetValue)),
					new XElement(
						"PropertyGroup",
						new XAttribute("Condition", "'$(UnityVisualStudioEditorActive)' == 'true' And '$(IsEntryPointProject)' != 'true' And '$(MSBuildProjectName)' != 'Main.EntryPoint'"),
						new XElement("UnityProjectGenerator", "Unity/MSBuild"),
						new XElement("UnityProjectGeneratorVersion", unityVersion),
						new XElement("UnityProjectGeneratorStyle", "SDK"),
						new XElement("UnityProjectType", "Game:1"),
						new XElement("UnityBuildTarget", buildTargetValue),
						new XElement("UnityVersion", unityVersion)),
					itemGroup));

			return document;
		}

		private static string GetProjectDirectory()
		{
			return IOPath.GetFullPath(IOPath.Combine(Application.dataPath, ".."));
		}

		private static bool WriteIfChanged(string path, string content)
		{
			try
			{
				if (File.Exists(path) && File.ReadAllText(path) == content)
					return true;

				Directory.CreateDirectory(IOPath.GetDirectoryName(path));
				File.WriteAllText(path, content);
				return true;
			}
			catch (IOException exception)
			{
				Debug.LogWarning($"Unable to update Visual Studio MSBuild integration: {exception.Message}");
				return false;
			}
			catch (UnauthorizedAccessException exception)
			{
				Debug.LogWarning($"Unable to update Visual Studio MSBuild integration: {exception.Message}");
				return false;
			}
		}

		internal static string EscapeForMSBuild(string value)
		{
			return value
				.Replace("%", "%25")
				.Replace("$", "%24")
				.Replace("@", "%40")
				.Replace("(", "%28")
				.Replace(")", "%29")
				.Replace("'", "%27")
				.Replace(";", "%3B")
				.Replace("?", "%3F")
				.Replace("*", "%2A");
		}
#endif
	}
}
